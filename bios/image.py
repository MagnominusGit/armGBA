# image.py bios.bin bios-image.c: writes the BIOS image as a C array.
import sys

data = open(sys.argv[1], 'rb').read()
lines = ['/* Copyright (c) 2026 Magnominus', ' *', ' * This Source Code Form is subject to the terms of the Mozilla Public', ' * License, v. 2.0. If a copy of the MPL was not distributed with this', ' * file, You can obtain one at http://mozilla.org/MPL/2.0/. */'] + ['// Generated by bios/build.sh from the sources in bios/. Don\'t edit.',
         '#include "gba.h"', '', 'const uint8_t armgbaBios[SIZE_BIOS] = {']
for i in range(0, len(data), 16):
    lines.append('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
lines.append('};')
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
